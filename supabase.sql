-- For a NEW Supabase project. Existing projects must be reviewed before migration.
-- Run manually in the Supabase SQL editor; the application never runs DDL.
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name varchar(180) not null,
  email varchar(180) not null unique,
  password varchar(255) not null,
  auth_provider varchar(20) not null default 'password',
  google_id varchar(255) unique,
  role varchar(20) not null default 'family' check (role in ('family','caregiver','company')),
  status varchar(20) not null default 'active' check (status in ('active','inactive')),
  company_name varchar(180), legal_name varchar(180), cnpj varchar(18) unique,
  phone varchar(20), contact_name varchar(120), cpf varchar(14) unique,
  specialties varchar(255), clinic_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists users_clinic_id_idx on public.users(clinic_id);
-- Passwords and personal data are accessible only through the Node backend.
-- Use a server-only Supabase service_role key. Do not grant browser access.
alter table public.users enable row level security;
revoke all on public.users from anon, authenticated;
